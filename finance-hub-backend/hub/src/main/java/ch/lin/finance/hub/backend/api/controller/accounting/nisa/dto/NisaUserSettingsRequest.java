package ch.lin.finance.hub.backend.api.controller.accounting.nisa.dto;

import jakarta.validation.constraints.DecimalMax;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotNull;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class NisaUserSettingsRequest {
    @NotNull
    @Min(0)
    @Max(200000)
    private Long monthlyGrowthContribution;

    @NotNull
    @Min(0)
    @Max(100000)
    private Long monthlyTsumitateContribution;

    @DecimalMin("-1.0")
    @DecimalMax("1.0")
    private Double nisaExpectedReturnRate;
}
